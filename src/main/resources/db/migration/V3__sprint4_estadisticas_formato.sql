ALTER TABLE torneos
    ADD COLUMN formato VARCHAR(40) NOT NULL DEFAULT 'LIGA';

-- Tabla de estadisticas por jugador por torneo
CREATE TABLE estadisticas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jugador_id      BIGINT NOT NULL,
    torneo_id       BIGINT NOT NULL,
    goles           INTEGER NOT NULL DEFAULT 0,
    asistencias     INTEGER NOT NULL DEFAULT 0,
    partidos_jugados INTEGER NOT NULL DEFAULT 0,
    tarjetas_amarillas INTEGER NOT NULL DEFAULT 0,
    tarjetas_rojas  INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_estadistica_jugador FOREIGN KEY (jugador_id) REFERENCES jugadores(id) ON DELETE CASCADE,
    CONSTRAINT fk_estadistica_torneo  FOREIGN KEY (torneo_id)  REFERENCES torneos(id)  ON DELETE CASCADE,
    CONSTRAINT uk_estadistica_jugador_torneo UNIQUE (jugador_id, torneo_id)
);

CREATE INDEX idx_estadisticas_torneo ON estadisticas(torneo_id);
